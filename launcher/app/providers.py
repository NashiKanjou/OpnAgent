"""LLM_Porting_Map -> OpenShell provider profiles + providers.

One profile per map entry. The REAL key is stored in the gateway credential
store (via `provider create --credential`); inside the sandbox the profile's
env var (OPNL_<i>) only ever holds the opaque placeholder that OpenShell
injects — the shim copies it into the Authorization header, and the
supervisor swaps it for the real key only at the bound endpoint.
"""

from __future__ import annotations

import re

import yaml

from .config import LLMEntry
from .policy import BIN_PY_PATH

PROFILE_CATEGORY = "inference"


def profile_id(entry: LLMEntry) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", entry.host.lower()).strip("-")
    return f"opn-{entry.index}-{slug}"


def provider_name(entry: LLMEntry) -> str:
    # OpenShell-side (gateway credential store + `sandbox create
    # --provider`); operator-invisible, deliberately stays the old opn<N>.
    return f"opn{entry.index}"


# Hermes-side name — what the webui model picker and `hermes model` show.
# The sandbox entrypoint uses it as the config.yaml providers.<name> key
# AND exports <NAME>_API_KEY (hermes' env key contract for a named
# provider once it is not the default runtime; without it, switching
# profiles fails "no API key was found. Set the <NAME>_API_KEY ...").
HERMES_PROVIDER_BASE = "OpnAgentAPI"


def hermes_provider_name(entry: LLMEntry) -> str:
    return f"{HERMES_PROVIDER_BASE}{entry.index}"


def profile_yaml(entry: LLMEntry) -> str:
    prefix = entry.path_prefix
    if prefix:
        # /v1/** and the bare prefix (e.g. GET /v1/models -> /v1/models,
        # but some clients probe /v1 itself).
        paths = [f"{prefix}/**", prefix]
    else:
        paths = ["/**"]
    endpoints = [
        {
            "host": entry.host,
            "port": entry.port,
            "path": p,
            "protocol": "rest",
            "access": "read-write",
            "enforcement": "enforce",
        }
        for p in paths
    ]
    doc = {
        "id": profile_id(entry),
        "display_name": f"OpnAgent LLM map #{entry.index} ({entry.host})",
        "description": "Generated by OpnAgent launcher from 'LLM_Porting_Map.json'.",
        "category": PROFILE_CATEGORY,
        "inference_capable": True,
        "credentials": [
            {
                "name": f"opn_key_{entry.index}",
                "env_vars": [entry.cred_env],
                "required": True,
                "auth_style": "bearer",
                "header_name": "authorization",
            }
        ],
        "discovery": {"credentials": [f"opn_key_{entry.index}"]},
        "endpoints": endpoints,
        # Scripts count as their interpreter: the shim runs under the
        # base image's system python (venv python symlinks there,
        # readlink -f). Same constant the pypi/url rules bind to —
        # policy.BIN_PY_PATH, OPN_SANDBOX_PYTHON-overridable.
        "binaries": [BIN_PY_PATH],
    }
    return yaml.safe_dump(doc, sort_keys=False)
